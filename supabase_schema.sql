-- Run this in Supabase SQL Editor.
create table if not exists public.nasheeds (
  id bigint generated by default as identity primary key,
  title text not null,
  artist text not null default 'Aamir Multimedia',
  cover_url text,
  audio_path text not null,
  created_at timestamptz not null default now()
);

alter table public.nasheeds enable row level security;

-- Everyone can view the published nasheed list.
create policy "Public can read nasheeds"
on public.nasheeds for select
to anon, authenticated
using (true);

-- Only authenticated admin accounts should be able to write.
-- IMPORTANT: create a private admin allow-list and policies before public launch.
-- Do not use a client-side hidden button as security.

insert into storage.buckets (id, name, public)
values ('nasheeds', 'nasheeds', true)
on conflict (id) do nothing;

create policy "Public can read nasheed audio"
on storage.objects for select
to anon, authenticated
using (bucket_id = 'nasheeds');

